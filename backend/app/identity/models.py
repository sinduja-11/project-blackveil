"""
Internal domain model for participant identities.

This module defines the Participant dataclass that holds ALL identity fields,
including the Ed25519 private key.  The private key MUST NOT be included in
any API response schema, logged, or serialised to any external surface.

Storage note
------------
Participant records are kept in an in-memory Python dict inside
IdentityRepository (see repository.py).  All records are lost when the
application process restarts.  This is intentional for the Phase-2 prototype.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass, field
from datetime import datetime, timezone

from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)


class ParticipantStatus(str, enum.Enum):
    """Lifecycle status of a registered participant."""

    ACTIVE = "ACTIVE"
    REVOKED = "REVOKED"


@dataclass
class Participant:
    """
    Internal identity record for a registered participant.

    Attributes
    ----------
    participant_id : str
        Unique identifier (UUID) generated by the server at registration time.
    public_key : Ed25519PublicKey
        The participant's Ed25519 public key.  Shared freely.
    _private_key : Ed25519PrivateKey
        The participant's Ed25519 private key.  MUST stay internal.
        Excluded from __repr__ and __str__ to prevent accidental logging.
    created_at : datetime
        UTC timestamp of registration.
    status : ParticipantStatus
        Current lifecycle status.  Defaults to ACTIVE.
    """

    participant_id: str
    public_key: Ed25519PublicKey
    # Leading underscore signals "private"; repr=False keeps it out of logs.
    _private_key: Ed25519PrivateKey = field(repr=False)
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    status: ParticipantStatus = field(default=ParticipantStatus.ACTIVE)

    def __repr__(self) -> str:
        """Safe repr — private key is intentionally omitted."""
        return (
            f"Participant("
            f"participant_id={self.participant_id!r}, "
            f"status={self.status!r}, "
            f"created_at={self.created_at.isoformat()!r}"
            f")"
        )
